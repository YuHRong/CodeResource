my_str = 'Hello world'
print('in 操作符查询字符是否存在于字符串中')

print('查询 Hello 是否在 my_str 中')
print('Hello' in my_str)  # True

print('查询 hey 是否在 my_str 中')
print('hey' in my_str)  # False

print('使用 len() 索引字符串长度')
print(len(my_str))  # 11

print('使用索引访问字符串中的字符')
print(my_str[0]) # H
print(my_str[6]) # w

print(my_str[-1]) # d
print(my_str[-2]) # l