
namespace p3;

public class Calculator
{
 public Calculator()
 {

 }

 // 计算方法
 public double CalculateAdd(double num1, double num2)
 {
  return num1 + num2;
 }

 public double CalculateSub(double num1, double num2)
 {
  return num1 - num2;
 }

 public double CalculateMob(double num1, double num2)
 {
  return num1 * num2;
 }

 public double CalculateDis(double num1, double num2)
 {
  return num1 / num2;
 }
}
